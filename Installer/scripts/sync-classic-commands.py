#!/usr/bin/env python3
"""Copy device-side adb shell bodies into Rust constants without executing scripts."""

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCES = ("device/install.sh", "device/remove.sh")


def commands(path):
    source = path.read_text()
    result = {}
    for match in re.finditer(r"\badb shell\s+", source):
        position = match.end()
        start = position
        quote = None
        command = ""
        while position < len(source):
            character = source[position]
            if quote is None and (character.isspace() or character in ";|)&<>"):
                break
            if character in "\"'" and quote is None:
                quote = character
            elif character == quote:
                quote = None
            elif character == "\\" and quote != "'" and position + 1 < len(source):
                following = source[position + 1]
                if quote is None or following in '\\$`"\n':
                    if following != "\n":
                        command += following
                    position += 1
                else:
                    command += character
            else:
                command += character
            position += 1
        if source[start : start + 1] in "\"'":
            line_number = source.count("\n", 0, match.start()) + 1
            result[line_number] = command
    return result


def render():
    output = (
        "// Device commands ported verbatim from Packaging/od/installer.\n"
        "// Generated by scripts/sync-classic-commands.py; control flow lives in engine.rs.\n"
    )
    seen = set()
    for source in SOURCES:
        path = ROOT / "Packaging/od/installer" / source
        lines = path.read_text().splitlines()
        found = commands(path)
        for index, line in enumerate(lines):
            marker = re.fullmatch(r"\s*# @installer-command ([A-Z_]+)\s*", line)
            if not marker:
                continue
            name = marker.group(1)
            if name in seen:
                raise ValueError(f"Duplicate command marker: {name}")
            seen.add(name)
            candidates = [number for number in found if index + 1 < number <= index + 4]
            if not candidates:
                raise ValueError(
                    f"No quoted adb shell command after {source}:{index + 1} ({name})"
                )
            number = min(candidates)
            output += (
                f"// Packaging/od/installer/{source}:{number}\n"
                f'pub const {name}: &str = r###"{found[number]}"###;\n'
            )
    if not seen:
        raise ValueError("No installer command markers found")
    return output


def main():
    argparse.ArgumentParser(description=__doc__).parse_args()
    target = ROOT / "Installer/crates/installer-core/src/classic_commands.rs"
    target.write_text(render())


if __name__ == "__main__":
    main()
